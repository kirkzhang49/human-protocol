// Returns the English catalog label in en mode, otherwise the original zh.
export function bl(label: string | undefined, language: GameLanguage): string {
  if (!label) return label ?? "";
  if (language !== "en") return label;
  const exact = CATALOG_LABELS_EN[label];
  if (exact) return exact;
  let translated = label;
  const keys = Object.keys(CATALOG_LABELS_EN).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (!key || key.length < 2) continue;
    translated = translated.split(key).join(CATALOG_LABELS_EN[key]);
  }
  return translated;
}
